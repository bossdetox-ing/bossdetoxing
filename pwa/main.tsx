import React from 'react';
import { createRoot } from 'react-dom/client';
import { messages as t } from '../src/content';
import { App } from '../src/app/App';
import { disguiseTitle } from '../src/domain/disguise';
import '../src/styles/global.css';
import './web.css';
import '../src/styles/clandrei.css';
import '../src/styles/skeuo.css';

document.documentElement.dataset.platform = 'web';
// The tab wears the last chosen disguise before the first render, so the real name never shows.
try {
  const icon = localStorage.getItem('bossdetox-disguise');
  if (icon && /^[a-z0-9-]+$/.test(icon)) {
    document.title = disguiseTitle(icon);
    const link = document.querySelector<HTMLLinkElement>('link[rel="icon"]');
    if (link) link.href = `/disguise/${icon}.svg`;
  }
} catch {
  // Storage blocked: the shell's default disguise stays until settings load.
}
// The clandrei palette (src/styles/clandrei.css) is the app's look.
document.documentElement.dataset.palette = 'clandrei';
// Trial: skeuomorphic keys (src/styles/skeuo.css). Delete this line and the import to revert.
document.documentElement.dataset.buttons = 'skeuo';
createRoot(document.getElementById('root')!).render(
  <React.StrictMode>
    <App />
  </React.StrictMode>,
);
// sw.js is generated by scripts/pwa.mjs after a build, so dev runs without it.
if (import.meta.env.PROD && 'serviceWorker' in navigator) {
  // A new version takes over as soon as it is cached. The open app reloads into it only
  // while hidden: hiding already locks and clears the session, so no typing is lost.
  const updating = !!navigator.serviceWorker.controller;
  let reloading = false;
  const reload = () => {
    if (reloading) return;
    reloading = true;
    location.reload();
  };
  navigator.serviceWorker.addEventListener('controllerchange', () => {
    if (!updating) return;
    if (document.visibilityState === 'hidden') reload();
    else
      document.addEventListener('visibilitychange', () => {
        if (document.visibilityState === 'hidden') reload();
      });
  });
  window.addEventListener('load', () => {
    const registered = navigator.serviceWorker.register('/sw.js');
    document.addEventListener('visibilitychange', () => {
      if (document.visibilityState === 'visible')
        void registered.then((registration) => registration.update()).catch(() => undefined);
    });
    void registered.catch(() => {
      const notice = document.createElement('p');
      notice.className = 'offline-error';
      notice.textContent = t.pwa.offlineFailed;
      notice.setAttribute('role', 'alert');
      document.body.append(notice);
    });
  });
}
